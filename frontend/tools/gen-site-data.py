"""One-off generator for lib/arena/siteData.ts. Not part of the build.

Inputs (from the Palace of Fine Arts project, https://github.com/dkhh10/palace-of-fine-arts-3d):
  site_local.json   reference/plans/site_local.json   OSM footprints, +x east / +y north, origin = rotunda centre
  manifest.json     web assets gate5 manifest         per-object `location_blender` (Blender Z-up)
Usage:  python -I tools/gen-site-data.py site_local.json manifest.json > lib/arena/siteData.ts

Coordinate maps (verified against the exported glb bbox and the manifest's hero camera):
  OSM (east, north)        -> three (x, z) = (-north, -east)
  Blender (x, y, z)        -> three (x, y, z) = (x, z, -y)
"""
import json, re, sys

site = json.load(open(sys.argv[1]))
man = json.load(open(sys.argv[2]))

def osm(p):  # (east, north) -> (x, z)
    return (round(-p[1], 1), round(-p[0], 1))

def poly(key):
    return [osm(p) for p in site[key][0]]

def fmt_poly(pts):
    return "[" + ",".join(f"[{x},{z}]" for x, z in pts) + "]"

cols = []
for name, a in man["assets"].items():
    loc = a.get("location_blender")
    if not loc:
        continue
    m = re.match(r"ARCH_(colonnade_north|colonnade_south|rotunda|rotunda_inner)_column_\d+_LOD0$", name)
    if not m:
        continue
    kind = {"colonnade_north": "c", "colonnade_south": "c", "rotunda": "r", "rotunda_inner": "i"}[m.group(1)]
    cols.append((kind, round(loc[0], 2), round(-loc[1], 2)))

small = [k for k in site if re.match(r"(w3\d\d|b317)", k)]  # the six ~2.4 m pylon squares (not the b302 hall)

out = []
out.append("// GENERATED by tools/gen-site-data.py - do not edit by hand.")
out.append("// Palace of Fine Arts site layout in three.js world space (1 unit = 1 m, origin = rotunda floor centre,")
out.append("// +Y up, the lagoon lies toward -Z). Source: OpenStreetMap footprints + the glb export manifest")
out.append("// of github.com/dkhh10/palace-of-fine-arts-3d (MIT code / CC BY-SA 4.0 assets).")
out.append("export type Pt = readonly [number, number]; // [x, z]")
out.append("export const WATER_Y = -1.3;")
out.append(f"export const LAGOON: Pt[] = {fmt_poly(poly('lagoon0'))};")
out.append(f"export const HALL: Pt[] = {fmt_poly(poly('b302 h20m'))};")
out.append(f"export const ROTUNDA_FOOTPRINT: Pt[] = {fmt_poly(poly('rotunda'))};")
out.append(f"export const COLONNADE_NORTH_ROOF: Pt[] = {fmt_poly(poly('roof310 h19'))};")
out.append(f"export const COLONNADE_SOUTH_ROOF: Pt[] = {fmt_poly(poly('roof306 h20'))};")
out.append("export const PYLONS: Pt[][] = [" + ",".join(fmt_poly(poly(k)) for k in small) + "];")
out.append("/** kind: r = rotunda outer ring, i = rotunda inner ring, c = colonnade column. [kind, x, z] */")
out.append("export const COLUMNS: ReadonlyArray<readonly [\"r\" | \"i\" | \"c\", number, number]> = [" + ",".join(f'["{k}",{x},{z}]' for k, x, z in cols) + "];")
print("\n".join(out))
